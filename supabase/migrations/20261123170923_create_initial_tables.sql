-- Auto-calculate quote_items.subtotal_cents in integer cents
create or replace function public.calculate_quote_item_subtotal()
returns trigger
language plpgsql
as $$
begin
  new.subtotal_cents := round(new.quantity * new.unit_price_snapshot_cents)::integer;
  return new;
end;
$$;

create trigger trg_quote_items_calculate_subtotal
  before insert or update of quantity, unit_price_snapshot_cents
  on public.quote_items
  for each row execute function public.calculate_quote_item_subtotal();

-- Auto-calculate quotes.total_cents & paid_at timestamp
create or replace function public.prepare_quote_before_write()
returns trigger
language plpgsql
as $$
begin
  new.total_cents := greatest(0, new.subtotal_cents + new.adversity_fee_cents - new.discount_cents);

  if new.status = 'paid' and (tg_op = 'INSERT' or old.status is distinct from 'paid') then
    new.paid_at := coalesce(new.paid_at, now());
  end if;

  return new;
end;
$$;

create trigger trg_quotes_prepare_before_write
  before insert or update of subtotal_cents, adversity_fee_cents, discount_cents, status
  on public.quotes
  for each row execute function public.prepare_quote_before_write();

-- Recalculate quotes.subtotal_cents whenever quote_items change
create or replace function public.sync_quote_subtotal_from_items()
returns trigger
language plpgsql
as $$
declare
  v_quote_id uuid;
  v_subtotal integer;
begin
  v_quote_id := coalesce(new.quote_id, old.quote_id);

  select coalesce(sum(subtotal_cents), 0)::integer
    into v_subtotal
    from public.quote_items
   where quote_id = v_quote_id;

  update public.quotes
     set subtotal_cents = v_subtotal
   where id = v_quote_id;

  return null;
end;
$$;

create trigger trg_quote_items_sync_quote_subtotal
  after insert or update or delete
  on public.quote_items
  for each row execute function public.sync_quote_subtotal_from_items();

-- Trigger: Quote status -> 'paid' creates 1 single income entry in financial_transactions
create or replace function public.create_cashbook_entry_on_quote_paid()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_paid_ts timestamptz;
  v_br_date date;
  v_billing_month text;
begin
  if new.status = 'paid'
     and old.status is distinct from 'paid'
     and new.total_cents > 0 then

    v_paid_ts := coalesce(new.paid_at, now());
    v_br_date := (v_paid_ts at time zone 'America/Sao_Paulo')::date;
    v_billing_month := to_char(v_br_date, 'YYYY-MM');

    insert into public.financial_transactions (
      type,
      status,
      description,
      category,
      amount_cents,
      due_date,
      paid_at,
      billing_month,
      quote_id
    )
    values (
      'income',
      'paid',
      format('Orçamento #%s — %s', new.quote_number, new.client_name),
      'Serviços / Orçamentos',
      new.total_cents,
      v_br_date,
      v_paid_ts,
      v_billing_month,
      new.id
    )
    on conflict (quote_id) where quote_id is not null do nothing;
  end if;

  return new;
end;
$$;

create trigger trg_quotes_create_cashbook_entry_on_paid
  after update of status
  on public.quotes
  for each row execute function public.create_cashbook_entry_on_quote_paid();

