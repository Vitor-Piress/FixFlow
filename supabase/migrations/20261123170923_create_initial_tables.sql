  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null default 'Manutenção Geral',
  unit public.unit_type not null default 'unit',
  base_price_cents integer not null check (base_price_cents >= 0),
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Materials catalog (Catálogo de Materiais e Peças)
create table public.materials (
  id uuid primary key default gen_random_uuid(),
  supplier_id uuid references public.suppliers(id) on delete set null,
  name text not null,
  unit public.unit_type not null default 'unit',
  unit_price_cents integer not null check (unit_price_cents >= 0),
  price_updated_at date not null default (now() at time zone 'America/Sao_Paulo')::date,
  notes text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Quotes (Orçamentos)
create table public.quotes (
  id uuid primary key default gen_random_uuid(),
  quote_number integer generated by default as identity unique not null,
  client_name text not null,
  client_phone text,
  client_address text,
  title text,
  status public.quote_status not null default 'draft',
  show_item_prices boolean not null default true,
  subtotal_cents integer not null default 0 check (subtotal_cents >= 0),
  adversity_fee_cents integer not null default 0 check (adversity_fee_cents >= 0),
  adversity_reason text,
  discount_cents integer not null default 0 check (discount_cents >= 0),
  total_cents integer not null default 0 check (total_cents >= 0),
  payment_terms text,
  notes text,
  valid_until date,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Quote items with frozen historical snapshot (Itens do Orçamento)
create table public.quote_items (
  id uuid primary key default gen_random_uuid(),
  quote_id uuid not null references public.quotes(id) on delete cascade,
  item_type public.quote_item_type not null,
  service_id uuid references public.services(id) on delete set null,
  material_id uuid references public.materials(id) on delete set null,
  description_snapshot text not null,
  unit_snapshot public.unit_type not null default 'unit',
  quantity numeric(10, 2) not null check (quantity > 0),
  unit_price_snapshot_cents integer not null check (unit_price_snapshot_cents >= 0),
  subtotal_cents integer not null default 0 check (subtotal_cents >= 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  constraint quote_items_single_source_check check (
    not (service_id is not null and material_id is not null)
  )
);

-- Monthly recurring contracts (Contratos Mensais)
create table public.contracts (
  id uuid primary key default gen_random_uuid(),
  client_name text not null,
  client_phone text,
  scope_description text,
  monthly_amount_cents integer not null check (monthly_amount_cents > 0),
  due_day smallint not null check (due_day between 1 and 31),
  pdf_path text,
  is_active boolean not null default true,
  started_at date not null default (now() at time zone 'America/Sao_Paulo')::date,
  ended_at date,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Recurring fixed expenses (Despesas Fixas Mensais)
create table public.recurring_expenses (
  id uuid primary key default gen_random_uuid(),
  description text not null,
  category text not null default 'Despesa Fixa',
  amount_cents integer not null check (amount_cents > 0),
  due_day smallint not null check (due_day between 1 and 31),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Financial transactions / Cashbook (Livro-Caixa)
create table public.financial_transactions (
  id uuid primary key default gen_random_uuid(),
  type public.transaction_type not null,
  status public.transaction_status not null default 'pending',
  description text not null,
  category text,
  amount_cents integer not null check (amount_cents > 0),
  due_date date not null,
  paid_at timestamptz,
  billing_month text not null check (billing_month ~ '^\d{4}-(0[1-9]|1[0-2])$'),
  quote_id uuid references public.quotes(id) on delete set null,
  contract_id uuid references public.contracts(id) on delete set null,
  recurring_expense_id uuid references public.recurring_expenses(id) on delete set null,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

