-- 6. RPC: IDEMPOTENT MONTHLY RECURRING TRANSACTIONS
-- ============================================================================
create or replace function public.generate_monthly_recurring_transactions(
  target_month text default null
)
returns integer
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_month text;
  v_month_start date;
  v_month_end date;
  v_days_in_month integer;
  v_contracts_inserted integer := 0;
  v_expenses_inserted integer := 0;
begin
  v_month := coalesce(
    target_month,
    to_char((now() at time zone 'America/Sao_Paulo')::date, 'YYYY-MM')
  );

  if v_month !~ '^\d{4}-(0[1-9]|1[0-2])$' then
    raise exception 'Invalid target_month format. Expected YYYY-MM, got: %', v_month;
  end if;

  v_month_start := to_date(v_month || '-01', 'YYYY-MM-DD');
  v_month_end := (v_month_start + interval '1 month - 1 day')::date;
  v_days_in_month := extract(day from v_month_end)::integer;

  -- Active monthly contracts -> pending income
  insert into public.financial_transactions (
    type,
    status,
    description,
    category,
    amount_cents,
    due_date,
    billing_month,
    contract_id
  )
  select
    'income',
    'pending',
    format('Contrato Mensal — %s', c.client_name),
    'Contratos Mensais',
    c.monthly_amount_cents,
    make_date(
      extract(year from v_month_start)::integer,
      extract(month from v_month_start)::integer,
      least(c.due_day::integer, v_days_in_month)
    ),
    v_month,
    c.id
  from public.contracts c
  where c.is_active = true
    and c.started_at <= v_month_end
    and (c.ended_at is null or c.ended_at >= v_month_start)
  on conflict (contract_id, billing_month) where contract_id is not null do nothing;

  get diagnostics v_contracts_inserted = row_count;

  -- Active recurring expenses -> pending expense
  insert into public.financial_transactions (
    type,
    status,
    description,
    category,
    amount_cents,
    due_date,
    billing_month,
    recurring_expense_id
  )
  select
    'expense',
    'pending',
    re.description,
    re.category,
    re.amount_cents,
    make_date(
      extract(year from v_month_start)::integer,
      extract(month from v_month_start)::integer,
      least(re.due_day::integer, v_days_in_month)
    ),
    v_month,
    re.id
  from public.recurring_expenses re
  where re.is_active = true
  on conflict (recurring_expense_id, billing_month) where recurring_expense_id is not null do nothing;

  get diagnostics v_expenses_inserted = row_count;

  return v_contracts_inserted + v_expenses_inserted;
end;
$$;

grant execute on function public.generate_monthly_recurring_transactions(text) to authenticated;

